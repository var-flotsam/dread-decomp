#!/usr/bin/env python3
"""Generate data/functions/main_XX.csv and data/reflection_types.csv.

Inputs (all regenerated by tools, never hand-edited):
  build/recon/<ver>/main_*.json        tools/recon/run.py
  build/ghidra_export/<ver>/main_*     tools/ghidra/analyze.py

data/functions/main_XX.csv holds the functions in the XX-th MiB of the module, split so
each file stays under the 1 MB pre-commit limit. Columns: address,size,name,name_source,subsystem,status
  address      absolute (image base 0x7100000000)
  size         bytes; from .eh_frame when available, else Ghidra's body extent
  name         best guess, demangled; fn_<addr> when unknown
  name_source  symbol | library | rtti | reflection | string | inferred | unknown
               (library = matched against vendored upstream code, data/library_symbols.csv;
               inferred = a name a person chose, from data/names.csv, tools/rename.py)
  subsystem    guess (see SUBSYSTEM_RULES); "?"-suffixed when inferred from neighbours
  status       BotW / nx-decomp-tools codes (see docs/references.md):
                 O matching, m non-matching (minor), M non-matching (major), W work in progress,
                 U not decompiled, L library (excluded from progress).
               O/m/M/W are set by tools/check.py from src/ and preserved here; every other
               function is L if its subsystem is a library, else U. Entries that are not written
               code are L too, with subsystem "import" (Ghidra's placeholders for imported
               functions, past the end of the module) or "linker" (PLT stubs and padding).

Usage: python tools/gen_functions_csv.py --version 2.1.0
"""

from __future__ import annotations

import argparse
import csv
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "recon"))
import reflection  # noqa: E402
from image import BASE, Image  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
import hostenv  # noqa: E402
from dread import names as name_map  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
CXXFILT = hostenv.cxxfilt()
GENERIC_NAME = re.compile(r"^(FUN_|thunk_FUN_|_INIT_\d+$|LAB_|SUB_|entry$)")

# First match wins. Applied to the best-guess name (or the reflected type name).
SUBSYSTEM_RULES = [
    (r"^nn::atk", "middleware/nn-atk"),
    (r"^nn::", "sdk"),
    (r"^(std::|__cxa|_Unwind|operator (new|delete)|malloc|free|calloc|realloc|aligned_alloc|mem(cpy|set|move|cmp)|str[a-z]+$)", "runtime"),
    (r"^(nninit|nnMain|nndetail|__nnDetail|_DT_(INIT|FINI))", "runtime"),
    # Metamethod tables (and the one with print) are the game's own userdata bindings, not the vendored
    # Lua: a library subsystem would make them status L, which nothing in lib/lua provides.
    (r"^lua_lib::", "script/bindings"),
    (r"^lua_bind::", "script/bindings"),
    (r"^base::reflection", "engine/reflection"),
    (r"^base::", "engine/base"),
    (r"^engine::", "engine"),
    (r"^GUI::", "gui"),
    (r"^(sound::|CSound|CMusic)", "audio"),
    (r"^behaviortree::", "ai/behaviortree"),
    (r"^querysystem::", "ai/querysystem"),
    (r"^navmesh::", "ai/navmesh"),
    (r"^animtree::", "animation"),
    (r"^(CCharClass|CChar)", "game/characters"),
    (r"^C\w*(Action|Attack|AI\w*)\b", "game/ai"),
    (r"^(CSamus|CPlayer)", "game/player"),
    (r"^C\w*Component\b", "game/components"),
    (r"^(CMinimap|CMap|CWorld|CScenario|CLevel|CArea)", "game/world"),
    (r"^(CGame|CPlaythrough|CBlackboard|CSave)", "game/core"),
    (r"^(CCutScene|CCutscene|CTimeline)", "game/cutscene"),
    (r"^(game|gameeditor|msapi|media)::", r"\1"),
    (r"^C[A-Z]\w*", "game"),
    (r"^S[A-Z]\w*", "game"),
]

# Code we don't decompile as game code: vendored upstream (Lua, dlmalloc), Nintendo
# middleware/SDK (nn::atk, nn::), and the C/C++ runtime. Marked L, like BotW's
# "library function" status, and excluded from progress.
LIBRARY_SUBSYSTEMS = {"middleware/nn-atk", "sdk", "runtime", "lua", "dlmalloc", "import", "linker"}
# Entries that are not code anyone wrote, so there is nothing to decompile (status L):
#   import  Ghidra's placeholders for imported functions (`<EXTERNAL>::...`), at addresses past the
#           end of the module; the import itself is declared in a header and, in the port, provided
#           by port/runtime or trapped by tools/port_link.py.
#   linker  PLT stubs (adrp x16; ldr x17; add x16; br x17), which the linker generates for every
#           imported function, and padding between functions (nop, or the 0xe7ffdefe filler).
PADDING_WORDS = {0xD503201F, 0xE7FFDEFE, 0x00000000}


def non_code(img: Image, addr: int, size: int) -> str | None:
    """"import" or "linker" for an entry that is not written code (see LIBRARY_SUBSYSTEMS), else None."""
    off = addr - BASE
    if off >= len(img.data):  # by address: Ghidra also gives PLT stubs and some thunks <EXTERNAL>:: names
        return "import"
    if size == 16 and off + 16 <= len(img.data):
        w = [img.u32(off + 4 * i) for i in range(4)]
        if (w[0] & 0x9F00001F == 0x90000010 and w[1] & 0xFFC003FF == 0xF9400211
                and w[2] & 0xFFC003FF == 0x91000210 and w[3] == 0xD61F0220):
            return "linker"
    if size % 4 == 0 and 0 < size <= 16 and off + size <= len(img.data)             and all(img.u32(off + i) in PADDING_WORDS for i in range(0, size, 4)):
        return "linker"
    return None
# Subsystems where a neighbour's inferred subsystem ("lua?") does not make a function library code:
# the game added its own functions to Lua's auxiliary library (luaL_testudata, ...), between ones
# tools/sigmatch.py matches to lib/lua, and nothing in lib/lua provides them. Only a matched name is
# library there. Likewise "runtime": the C++ library's templates are instantiated in the game's own
# units (GUI::CSlotInfoComposition's unit holds four std::basic_stringstream thunks), and an inferred
# "runtime?" made the class's constructor, virtual getter and helpers library code that nothing
# generated or lifted (the port trapped on them after a press on the title, 2026-11-08).
INFERRED_NOT_LIBRARY = {"lua", "runtime"}


def is_library(subsystem: str, name_source: str) -> bool:
    """Whether a function of `subsystem` ("x?" when inferred from its neighbours) is library code (L).
    In an INFERRED_NOT_LIBRARY subsystem an inferred one is library only when its name says so (a
    symbol or a match against vendored code: the std::basic_stringstream thunks in a GUI unit)."""
    base_sub = subsystem.rstrip("?")
    if base_sub not in LIBRARY_SUBSYSTEMS:
        return False
    if subsystem.endswith("?") and base_sub in INFERRED_NOT_LIBRARY:
        return name_source in ("symbol", "library")
    return True


# Statuses that come from src/ (tools/check.py) and must survive regeneration.
DECOMP_STATUSES = {"O", "m", "M", "W"}

# Lua 5.1 standard-library tables are recognised by their first entry.
LUA_STDLIB_FIRST = {"assert", "abs", "byte", "concat", "create", "close", "clock", "loadlib", "debug"}


def demangle(names: list[str]) -> list[str]:
    if not names:
        return []
    out = subprocess.run([CXXFILT], input="\n".join(names), capture_output=True, text=True,
                         check=True).stdout.splitlines()
    return [o.split("(")[0] if o != n else n for o, n in zip(out, names)]


def subsystem_for(name: str) -> str | None:
    for pat, sub in SUBSYSTEM_RULES:
        m = re.match(pat, name)
        if m:
            return m.expand(sub) if "\\" in sub else sub
    return None


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--version", required=True)
    args = ap.parse_args()
    recon = ROOT / "build" / "recon" / args.version
    export = ROOT / "build" / "ghidra_export" / args.version

    eh = {int(a, 16): n for a, n in json.loads((recon / "main_eh_functions.json").read_text())}
    ghidra = {int(f["entry"], 16): f for f in map(json.loads, open(export / "main_functions.jsonl"))}
    funcs: dict[int, int] = dict(eh)
    for a, f in ghidra.items():
        funcs.setdefault(a, int(f["max"], 16) - a + 1)

    names: dict[int, tuple[str, str]] = {}  # addr -> (name, source)

    def put(addr: int, name: str, source: str) -> None:
        if addr in funcs and addr not in names:
            names[addr] = (name, source)

    # 1. Dynamic symbols (exports) and Ghidra-applied symbol names (PLT stubs, SDK entry points).
    dyn = [d for d in json.loads((recon / "main_dynsym.json").read_text()) if d["kind"] == "export"]
    for d, n in zip(dyn, demangle([d["name"] for d in dyn])):
        put(int(d["value"], 16), n, "symbol")
    gnames = [(a, f["name"]) for a, f in ghidra.items() if not GENERIC_NAME.match(f["name"])]
    for (a, raw), n in zip(gnames, demangle([g for _, g in gnames])):
        put(a, n, "symbol")

    # 1b. Library code identified by matching vendored upstream sources (tools/sigmatch.py).
    library_subsystem: dict[int, str] = {}
    lib_csv = ROOT / "data" / "library_symbols.csv"
    if lib_csv.is_file():
        with lib_csv.open(newline="", encoding="utf-8") as f:
            for r in csv.DictReader(f):
                a = int(r["address"], 16)
                put(a, r["name"], "library")
                library_subsystem[a] = r["library"]

    # 2. RTTI: virtual functions of nn::atk classes, owned by the base-most class using them.
    rtti = json.loads((recon / "main_rtti.json").read_text())
    depth = {}

    def class_depth(ti: dict, by_addr: dict) -> int:
        if ti["typeinfo"] not in depth:
            depth[ti["typeinfo"]] = 1 + max((class_depth(by_addr[b["typeinfo"]], by_addr)
                                             for b in ti["bases"] if b["typeinfo"] in by_addr), default=0)
        return depth[ti["typeinfo"]]

    by_addr = {t["typeinfo"]: t for t in rtti}
    owners: dict[int, tuple[int, str, int]] = {}
    for t in rtti:
        for vt in t["vtables"]:
            if vt["offset_to_top"] != 0:
                continue
            for i, s in enumerate(vt["slots"]):
                if not s.startswith("0x"):
                    continue
                a, d = int(s, 16), class_depth(t, by_addr)
                if a not in owners or d < owners[a][0]:
                    owners[a] = (d, t["name"], i)
    for a, (_, cls, i) in owners.items():
        # Tiny bodies (e.g. a bare `ret`) are folded by the linker and shared by unrelated
        # vtables, so the owner would be arbitrary.
        if funcs.get(a, 0) > 8:
            put(a, f"{cls}::vf_{8 * i:#x}", "rtti")

    # 3. Reflection: per-type class getters and descriptor init helpers.
    from mercury_engine_data_structures import dread_data
    img = Image(ROOT / "orig" / args.version / "exefs" / "main")
    types = reflection.recover(img, export, dread_data.get_raw_types())
    helper_users: dict[int, int] = {}
    for t in types.values():
        if t.init_helper is not None:
            helper_users[t.init_helper] = helper_users.get(t.init_helper, 0) + 1
    for t in types.values():
        if t.kind == "class":
            put(t.getter, f"{t.name}::refl_GetClass", "reflection")
            if t.init_helper is not None and helper_users[t.init_helper] == 1:
                put(t.init_helper, f"{t.name}::refl_InitClass", "reflection")
        else:
            put(t.getter, f"base::reflection::refl_GetType<{t.name}>", "reflection")
            if t.init_helper is not None and helper_users[t.init_helper] == 1:
                put(t.init_helper, f"base::reflection::refl_InitType<{t.name}>", "reflection")

    # 3b. Reflection: each class's attribute and member-field functions and the per-type functions its
    # descriptor points to, under their roles (T::refl_Equals, T::refl_AddFields, ...; the names
    # tools/gen_reflection.py writes them under, base/reflection/ReflectedClass.h).
    import asmdiff
    import gen_reflection
    orig = asmdiff.Original(args.version)
    class_getters = {t.getter for t in types.values() if t.kind == "class"}
    unique_inits = {t.init_helper for t in types.values()
                    if t.kind == "class" and t.init_helper is not None and helper_users[t.init_helper] == 1}
    for t in sorted(types.values(), key=lambda t: t.getter):
        if t.kind == "class" and t.init_helper in unique_inits:
            g = gen_reflection.Getter(t.name, t.getter)
            gen_reflection.analyse(orig, g, class_getters, "", unique_inits)
            for a, n in sorted(gen_reflection.reflection_names(g).items()):
                put(a, n, "reflection")

    # 4. Strings: Lua C-function binding tables.
    lua = json.loads((recon / "main_lua_tables.json").read_text())
    seen_lua: dict[str, int] = {}
    for tbl in lua:
        ns = "lua_lib" if tbl["entries"][0]["name"] in LUA_STDLIB_FIRST or tbl["entries"][0]["name"].startswith("__") \
            else "lua_bind"
        for e in tbl["entries"]:
            key = f"{ns}::{e['name']}"
            seen_lua[key] = seen_lua.get(key, 0) + 1
            name = key if seen_lua[key] == 1 else f"{key}_{tbl['addr'][-6:]}"
            put(int(e["func"], 16), name, "string")

    # 5. Names people chose (data/names.csv, tools/rename.py), for functions the binary does not name. They
    # are applied to the written rows only, after the subsystems: a chosen name never moves a function to
    # another subsystem or status, so tools/rename.py writes the same row this does (dread.names.apply).
    chosen = name_map.read()
    chosen_names: dict[int, tuple[str, str]] = {}
    problems = name_map.row_problems(chosen)
    for r in chosen:
        a = int(r["address"], 16)
        if a not in funcs:
            problems.append(f"{r['address']} ({r['name']}): not a function of the module")
        elif a in names and names[a][0] != r["name"]:
            problems.append(f"{r['address']} ({r['name']}): the binary names it {names[a][0]} ({names[a][1]})")
        else:
            chosen_names[a] = (r["name"], r["name_source"])
    if problems:
        raise SystemExit("data/names.csv:\n  " + "\n  ".join(problems))

    # Subsystems: from the name; otherwise from the nearest named neighbours if they agree.
    ordered = sorted(funcs)
    sub: dict[int, str] = {}
    for a in ordered:
        if a in library_subsystem:
            sub[a] = library_subsystem[a]
        elif a in names:
            owner = names[a][0]
            s = subsystem_for(owner)
            if s:
                sub[a] = s
    named_idx = [i for i, a in enumerate(ordered) if a in sub]
    for left, right in zip(named_idx, named_idx[1:]):
        if sub[ordered[left]] == sub[ordered[right]] and right - left <= 64:
            for i in range(left + 1, right):
                sub.setdefault(ordered[i], sub[ordered[left]] + "?")

    for a in ordered:
        kind = non_code(img, a, funcs[a])
        if kind:
            sub[a] = kind

    # One file per MiB of address space keeps each under the 1 MB pre-commit limit.
    out_dir = ROOT / "data" / "functions"
    out_dir.mkdir(parents=True, exist_ok=True)
    old_status = {}
    for old in out_dir.glob("main_*.csv"):
        with old.open(newline="") as f:
            old_status.update({r["address"]: r["status"] for r in csv.DictReader(f)})
        old.unlink()
    chunks: dict[int, list[int]] = {}
    for a in ordered:
        chunks.setdefault((a - BASE) >> 20, []).append(a)
    for idx, addrs in chunks.items():
        with (out_dir / f"main_{idx:02x}.csv").open("w", newline="", encoding="utf-8") as f:
            w = csv.writer(f, lineterminator="\n")
            w.writerow(["address", "size", "name", "name_source", "subsystem", "status"])
            for a in addrs:
                name, source = names.get(a, (f"fn_{a:x}", "unknown"))
                addr = f"{a:#x}"
                subsystem = sub.get(a, "unknown")
                status = old_status.get(addr)
                if status not in DECOMP_STATUSES:
                    status = "L" if is_library(subsystem, source) else "U"
                name, source = chosen_names.get(a, (name, source))
                w.writerow([addr, funcs[a], name, source, subsystem, status])

    rt = ROOT / "data" / "reflection_types.csv"
    with rt.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["type", "kind", "parent", "size", "getter"])
        for t in sorted(types.values(), key=lambda t: t.name):
            w.writerow([t.name, t.kind or "", (t.parent or "") if t.kind == "class" else "", f"{t.size:#x}" if t.size else "", f"{t.getter:#x}"])

    total = len(ordered)
    by_src: dict[str, int] = {}
    for a in ordered:
        s = names.get(a, ("", "unknown"))[1]
        by_src[s] = by_src.get(s, 0) + 1
    print(f"{total} functions; named {total - by_src.get('unknown', 0)} "
          f"({(total - by_src.get('unknown', 0)) / total:.1%}); by source: {by_src}")
    print(f"{len(types)} reflected types written to {rt.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
