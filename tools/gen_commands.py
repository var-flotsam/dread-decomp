#!/usr/bin/env python3
"""Generate docs/commands.md: every tool's one-line purpose and usage lines, from its docstring.

The command index used to be a hand-kept list in CLAUDE.md that every session loaded and that
went stale as tools changed. Each tool's module docstring already opens with its purpose and lists
its `python tools/...` usage lines; this collects them by group. Edit the docstring, then rerun.

Usage: python tools/gen_commands.py            # rewrite docs/commands.md
       python tools/gen_commands.py --check    # exit 1 if docs/commands.md is out of date (CI)
"""

from __future__ import annotations

import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "commands.md"

# Group of each tool, in the order a new clone needs them. A tool not listed lands in "Other",
# which the check reports, so a new tool gets a group when it is added.
GROUPS: list[tuple[str, list[str]]] = [
    ("Setup and the dump", ["setup", "verify_dump", "nso2elf", "fetch_toolchains", "fetch_sources"]),
    ("Reconnaissance", ["recon/run", "ghidra/analyze", "ghidra/export", "ghidra/decompile", "gen_functions_csv",
                        "sigmatch", "tu_map", "callgraph", "abi_facts", "compiler_matrix", "libcheck_lua"]),
    ("Generators (maintenance)", ["gen_reflection", "gen_types", "gen_statics", "gen_clones", "gen_tables",
                                  "gen_lift", "gen_class_getters"]),
    ("Matching", ["trymatch", "asmdiff", "nearcopy", "hubs", "shape_census", "objdiff_gen"]),
    ("Checks and progress", ["check", "verify", "progress", "policy_check", "decl_check", "dashboard_export",
                             "gen_commands"]),
    ("Header migrations", ["hub_migrate", "baseline"]),
    ("Port", ["port_sweep", "port_link", "port_lift", "port_addresses", "port_imports", "test_port_loader",
              "nvn_procs", "bshdat", "pcode_emu", "ghidra/pcode"]),
]
# Modules imported by other tools, not run on their own.
LIBRARIES = {"buildcfg", "hostenv", "nso", "refl_attrs", "ghidra/common"}


def tools() -> dict[str, Path]:
    found = {}
    for p in sorted((ROOT / "tools").rglob("*.py")):
        rel = p.relative_to(ROOT / "tools").with_suffix("").as_posix()
        if rel.startswith(("hooks/", "dread/", "tests/")) or rel.endswith(("__init__", "__main__")) or rel in LIBRARIES:
            continue
        if "/" in rel and rel.split("/")[0] == "recon" and rel != "recon/run":
            continue
        found[rel] = p
    return found


def entry(name: str, path: Path) -> list[str]:
    doc = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8"))) or ""
    lines = doc.splitlines()
    purpose = []
    for ln in lines:
        if not ln.strip():
            break
        purpose.append(ln.strip())
    usage = []
    for ln in lines:
        ln = ln.strip()
        if ln.lower().startswith("usage:"):
            ln = ln[len("usage:"):].strip()
        if ln.startswith("python ") and "tools/" in ln:
            usage.append(ln[len("python "):])
    out = [f"### `tools/{name}.py`", "", " ".join(purpose) or "(no docstring)", ""]
    if usage:
        out += ["```sh", *(f"python {u}" for u in usage), "```", ""]
    return out


def render() -> tuple[str, list[str]]:
    found = tools()
    listed = {n for _, names in GROUPS for n in names}
    other = sorted(set(found) - listed)
    md = ["# Commands", "",
          "Generated by `tools/gen_commands.py` from each tool's docstring; edit the docstring and rerun,",
          "never this page. Run tools with the repository's venv (`.venv/Scripts/python` on Windows,",
          "`.venv/bin/python` elsewhere). Setup order for a new clone: `docs/reference.md`,",
          "\"Rebuilding everything from scratch\".", ""]
    for title, names in GROUPS + ([("Other", other)] if other else []):
        md += [f"## {title}", ""]
        for n in names:
            if n in found:
                md += entry(n, found[n])
    return "\n".join(md).rstrip() + "\n", other


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if docs/commands.md is out of date")
    args = ap.parse_args()
    text, other = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text or other:
            if other:
                print(f"gen_commands: no group for {', '.join(other)} (add it to GROUPS)")
            if current != text:
                print("gen_commands: docs/commands.md is out of date; run python tools/gen_commands.py")
            return 1
        print("gen_commands: docs/commands.md is current")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"docs/commands.md: {text.count('### ')} tools" + (f"; ungrouped: {', '.join(other)}" if other else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
