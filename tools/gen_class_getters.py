#!/usr/bin/env python3
"""Generate include/base/reflection/UnkClassGetters.h: one declaration per reflected class getter.

Every reflected class T has a getter (T::refl_GetClass) that returns its guarded static
descriptor, defined in src/reflection/ by tools/gen_reflection.py through DREAD_REFL_CLASS_GETTER
(include/base/reflection/CClass.h):

    const base::reflection::CClass* fn_<addr>();

Hand-written sources used to declare the getters they call locally, each with its own guess at
the return type (void*, const CClass*, UnkClass* ...), which is what tools/decl_check.py counts as
conflicting signatures. This writes the one declaration of each getter, read from
data/functions/*.csv alone (the rows whose name ends in `::refl_GetClass` and whose name_source is
`reflection`), sorted by address, with the class name as a trailing comment. CClass is only
forward-declared, so including the header is cheap; sources that use the descriptor's members
include base/reflection/CClass.h as well.

No game data is needed. `--version` is accepted for uniformity with the other generators
(tools/verify.py --regen) and ignored: the function list is not per version.

Usage: python tools/gen_class_getters.py [--version 2.1.0]
Output is deterministic. Regenerate, never edit it.
"""

from __future__ import annotations

import argparse
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "include" / "base" / "reflection" / "UnkClassGetters.h"
SUFFIX = "::refl_GetClass"

HEADER = """\
#pragma once

// Generated by tools/gen_class_getters.py from data/functions/*.csv; regenerate rather than edit:
//   python tools/gen_class_getters.py
//
// The class getter (T::refl_GetClass) of every reflected class, declared once: it returns T's
// guarded static descriptor and is defined in src/reflection/ (tools/gen_reflection.py, through
// DREAD_REFL_CLASS_GETTER in base/reflection/CClass.h). Hand-written sources include this instead
// of declaring the getters they call. CClass is only forward-declared here, so including this is
// cheap; include "base/reflection/CClass.h" to use the descriptor's members.

namespace base::reflection {
class CClass;
}
"""


def getters() -> list[tuple[int, str]]:
    """(address, class name) of every reflected class getter in data/functions/, sorted by address."""
    out = []
    for path in sorted((ROOT / "data" / "functions").glob("main_*.csv")):
        with path.open(newline="", encoding="utf-8") as f:
            for row in csv.DictReader(f):
                name = row["name"]
                if row["name_source"] == "reflection" and name.endswith(SUFFIX):
                    cls = name[: -len(SUFFIX)]
                    if not cls or "\n" in cls or "\r" in cls:
                        raise SystemExit(f"{path.name}: unusable class name for {row['address']}: {name!r}")
                    out.append((int(row["address"], 16), cls))
    out.sort()
    addrs = [a for a, _ in out]
    if len(set(addrs)) != len(addrs):
        raise SystemExit("duplicate getter addresses in data/functions/")
    return out


def render(rows: list[tuple[int, str]]) -> str:
    lines = [HEADER]
    for addr, cls in rows:
        lines.append(f"const base::reflection::CClass* fn_{addr:010x}();  // {cls}::refl_GetClass")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--version", help="ignored; accepted for uniformity with the other generators")
    ap.parse_args()
    rows = getters()
    if not rows:
        raise SystemExit("no reflected class getters found in data/functions/")
    text = render(rows)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}: {len(rows)} class getters, {len(text)} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
